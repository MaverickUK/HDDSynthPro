"""Turns welcome/README.TXT into src/welcome_text.h, the README.TXT on the
drive's welcome disk (src/welcome_disk.*). PlatformIO runs it before each
build (extra_scripts in platformio.ini), and test/run_native_tests.sh before
the host tests. The header is git-ignored, like the .pio.h files.

The text must be plain ASCII, so DOS and every other computer show it the
same, with lines of at most 80 characters (DOS's screen). Line endings become
CRLF, which DOS needs. {VERSION} becomes FIRMWARE_VERSION from src/version.h.
The file's date on the disk is README.TXT's modification date.

Usage: python3 scripts/embed_welcome.py [project folder]
"""
from __future__ import annotations

import datetime
import os
import re
import sys

MAX_LINE = 80


def fat_date(day: datetime.date) -> int:
    """FAT's date format: (year - 1980) << 9 | month << 5 | day."""
    return (day.year - 1980) << 9 | day.month << 5 | day.day


def c_string(line: str) -> str:
    return '"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\r\\n"'


def build(project: str) -> str:
    """Writes the header if its content changed; returns its path."""
    source = os.path.join(project, "welcome", "README.TXT")
    header = os.path.join(project, "src", "welcome_text.h")
    with open(source, "rb") as f:
        raw = f.read()
    with open(os.path.join(project, "src", "version.h"), encoding="ascii") as f:
        version = re.search(r'#define FIRMWARE_VERSION "([^"]+)"', f.read()).group(1)

    lines = raw.replace(b"\r\n", b"\n").split(b"\n")
    if lines and lines[-1] == b"":
        lines.pop()  # the final newline
    text = []
    for number, line in enumerate(lines, 1):
        bad = [b for b in line if not (0x20 <= b <= 0x7E)]
        if bad:
            raise ValueError(f"{source}:{number}: only plain ASCII text, no tabs "
                             f"(found byte {bad[0]:#04x})")
        line = line.decode("ascii").replace("{VERSION}", version)
        if len(line) > MAX_LINE:
            raise ValueError(f"{source}:{number}: {len(line)} characters; at most {MAX_LINE}")
        text.append(line)

    date = datetime.date.fromtimestamp(os.path.getmtime(source))
    body = "\n".join(f"    {c_string(line)}" for line in text) or '    ""'
    content = (
        "// Generated by scripts/embed_welcome.py from welcome/README.TXT: edit that,\n"
        "// not this.\n"
        "#pragma once\n"
        "\n"
        "#include <cstdint>\n"
        "\n"
        "namespace welcome_text {\n"
        "\n"
        f"constexpr uint16_t FAT_DATE = {fat_date(date):#06x};  // {date.isoformat()}\n"
        "\n"
        "constexpr char README[] =\n"
        f"{body};\n"
        "constexpr uint32_t README_SIZE = sizeof README - 1;\n"
        "\n"
        "}  // namespace welcome_text\n"
    )
    try:
        with open(header, encoding="ascii") as f:
            if f.read() == content:
                return header
    except FileNotFoundError:
        pass
    with open(header, "w", encoding="ascii", newline="\n") as f:
        f.write(content)
    return header


if __name__ == "__main__":
    try:
        build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), ".."))
    except ValueError as e:
        sys.exit(f"embed_welcome: {e}")
else:
    Import("env")  # noqa: F821 (PlatformIO's SCons runs this before each build)
    try:
        build(env.subst("$PROJECT_DIR"))  # noqa: F821
    except ValueError as e:
        print(f"embed_welcome: {e}")
        env.Exit(1)  # noqa: F821
